import Foundation

/// 音质**档位** —— 四档，从低到高：`SD` → `HQ` → `SQ` → `HR`。
///
/// 🔴 **这个文件只管"有哪几档、各叫什么"**；「一首歌是哪一档」是纯函数，
/// 在 `Track+AudioQuality.swift`（吃已存的字段，不重读文件）。
///
/// ⚠️ **为什么是四档不是五档**：常见做法是从 Apple Music 搬来的，
/// 有五个档（多一个灰色档）。定去掉灰档 ⇒ 剩四档，
/// **DSD 并入最高档 `HR`**（不再单独一档）。
///
/// ⚠️ 显式写 `Hashable`（无关联值的枚举本来就自动满足，写出来是为了让人一眼看到
/// 「它会作为值类型的一部分被比较 / 进集合」，`AudioQualityTag` 合成 `Hashable` 也靠它）。
enum AudioQualityLevel: Hashable {

    /// 有损、码率也不高。
    case sd

    /// 有损、码率够高（≥ 320 kbps）。
    case hq

    /// 无损。
    case sq

    /// 高解析度（采样率 ≥ 88.2 kHz **或** 位深 ≥ 24）**或 DSD**。
    case hr

    /// 徽章上那两个字。
    var text: String {
        switch self {
        case .sd: "SD"
        case .hq: "HQ"
        case .sq: "SQ"
        case .hr: "HR"
        }
    }
}

/// **播放页**那条音质信息要画的**两样东西**：一行说明文字 ＋ 一枚档位徽章。
///
/// 🔴 **为什么捆成一个值**：它们**同生同灭** —— 都从同一份标签字段算出来，
/// 「这首歌有没有音质信息」对两者是**同一个问题**。拆成两个可选字段的话，
/// 「要么都有、要么都没有」这条不变量就只能靠人记着；而它一破，画出来就是半条空的
/// （有徽章没文字、或者反过来）。
///
/// ⚠️ `text` **永不为空**：「一条都没有」用 `nil`（整个 `AudioQualityLine` 缺席）表达。
struct AudioQualityLine: Equatable {

    /// 说明文字。**三段拼起来，中间用 `" · "` 隔**，第三段是"位深/采样率"合成的一项：
    ///
    /// | 编码 | 例子 |
    /// |---|---|
    /// | 无损（位深和采样率都有） | `FLAC · 16bit/44.1kHz` |
    /// | 无损（只有码率） | `FLAC · 1000kbps/44.1kHz` |
    /// | 有损 | `MP3 · 320kbps/44.1kHz` |
    /// | DSD | `DSD Stream · DSD` |
    ///
    /// 🔴 **`16bit/44.1kHz` 是一项、不是两项**（中间 `/`、两边**没有空格**）。
    /// ⚠️ 曾经写成 `FLAC · 44.1 kHz · 16 bit · 1000 kbps`（三项分开、带空格）——
    /// 那是**照着数据字段的个数**拼的，出来和这一行的口径对不上。
    ///
    /// ⚠️ **不写单位换算**：码率的单位**就是 kbps**（库里存的就是它），
    /// 采样率一律 `kHz`（不到 1000 Hz 才写 `Hz`）。
    let text: String

    /// 档位 —— 徽章画它。
    let level: AudioQualityLevel
}

/// **列表行**那一小枚要画的**两样东西**：格式名 ＋ 一枚档位徽章（`FLAC` ＋ `SQ`）。
///
/// 🔴 跟 `AudioQualityLine` 是**同一件事的两种呈现**，不是两个概念：
/// - 播放页地方大 ⇒ 要"说全"的那一行（格式 ＋ 位深/采样率，或格式 ＋ 码率/采样率）；
/// - 列表行只有一行字那么高 ⇒ 只放得下**格式名**。
///
/// 两者都捆着同一个 `level`：**「这首歌是哪一档」只有一个答案**，两处都从它来
/// （`Track.audioQualityLevel`，纯函数）。
///
/// ⚠️ 跟 `AudioQualityLine` 一样，`format` **永不为空** —— 「没有格式名」用 `nil`
/// （整个值缺席）表达，不用空串。这样「这一枚画不画」只有一个判据。
struct AudioQualityTag: Hashable {

    /// 格式名，比如 `FLAC` / `ALAC` / `MP3`。
    let format: String

    /// 档位 —— 徽章画它。
    let level: AudioQualityLevel
}

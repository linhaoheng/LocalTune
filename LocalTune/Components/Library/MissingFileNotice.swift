import Foundation

/// 「这首歌的文件不在本机」那一句提示 —— **文案的唯一出处**。
///
/// 曲库列表、歌单详情列表两处都用它；禁止两边各手写一句、日后漂移
///（跟 `LibraryTrackDeleteConfirmation` 同一条理由）。
///
/// 🔴 **刻意不写「播放失败」** —— 那是另一件事：播放失败是"文件在、但解不开"，
/// 两者的出路完全不同（一个要重新导入，一个要换一份文件）。
/// 这首歌的问题是**文件根本不在**，说成"播放失败"会让用户去查解码器，方向就错了。
enum MissingFileNotice {

    /// 弹一句提示 —— 浮层自己会消失，不用谁去收。
    static func show() {
        HUD.showMessage(title, detail: detail)
    }

    /// 主文案：**只说出状态**，不加感叹号。
    static let title = "文件不在本机"

    /// 第二行：说清"记录还在"（收藏 / 歌单 / 播放次数都还在），以及文件可能去哪儿了。
    static let detail = "这首歌的记录还在，但音乐文件不在本机了 —— 可能没同步下来，或者被移走了"
}

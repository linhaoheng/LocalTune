// MARK: - 色值容器

/// 一个色值在浅色 / 深色两种外观下的取值。
///
/// 存的是 `UInt32`，出口是 `UIColor`（见下面的 `uiColor`）。
/// `hasAlpha` 为 true 时低 8 位是 alpha（`0xRRGGBBAA`），否则是 `0xRRGGBB`。
struct RadixColor: Hashable, Sendable {
    let light: UInt32
    let dark: UInt32
    let hasAlpha: Bool

    init(light: UInt32, dark: UInt32, hasAlpha: Bool = false) {
        self.light = light
        self.dark = dark
        self.hasAlpha = hasAlpha
    }

    /// 随系统深浅外观自动切换。
    var uiColor: UIColor {
        UIColor { trait in
            Self.makeUIColor(
                trait.userInterfaceStyle == .dark ? self.dark : self.light,
                hasAlpha: self.hasAlpha
            )
        }
    }

    /// 在动态色基础上再叠一层透明度 —— 仍然跟随系统深浅。
    ///
    /// 没有写成 `uiColor.withAlphaComponent(value)`：那要赌「系统会不会把动态性一起带过去」。
    /// 这里在外层再包一个动态色 —— 浅深各自解析完，再叠 alpha，不依赖任何假设。
    func alpha(_ value: CGFloat) -> UIColor {
        UIColor { trait in
            let base = Self.makeUIColor(
                trait.userInterfaceStyle == .dark ? self.dark : self.light,
                hasAlpha: self.hasAlpha
            )
            return base.withAlphaComponent(value)
        }
    }

    /// 固定取某一种外观下的颜色（**不跟随系统**）。
    func uiColor(for style: UIUserInterfaceStyle) -> UIColor {
        Self.makeUIColor(style == .dark ? dark : light, hasAlpha: hasAlpha)
    }

    /// `0xRRGGBB` / `0xRRGGBBAA` → `UIColor`。
    private static func makeUIColor(_ value: UInt32, hasAlpha: Bool) -> UIColor {
        if hasAlpha {
            return UIColor(
                red:   CGFloat((value >> 24) & 0xFF) / 255,
                green: CGFloat((value >> 16) & 0xFF) / 255,
                blue:  CGFloat((value >>  8) & 0xFF) / 255,
                alpha: CGFloat( value        & 0xFF) / 255
            )
        }
        return UIColor(
            red:   CGFloat((value >> 16) & 0xFF) / 255,
            green: CGFloat((value >>  8) & 0xFF) / 255,
            blue:  CGFloat( value        & 0xFF) / 255,
            alpha: 1
        )
    }
}


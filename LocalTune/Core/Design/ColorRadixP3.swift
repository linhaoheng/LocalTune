import UIKit

// MARK: - 色值容器

/// 一个 Display P3 色值：三个颜色分量 + alpha，范围都是 0…1。
///
/// 存的**只是数字**，出口是下面的 `RadixP3Color`。
struct RadixP3: Hashable, Sendable {
    let red: Double
    let green: Double
    let blue: Double
    let alpha: Double

    init(_ red: Double, _ green: Double, _ blue: Double, _ alpha: Double = 1) {
        self.red = red
        self.green = green
        self.blue = blue
        self.alpha = alpha
    }
}

/// 一个色值在浅色 / 深色两种外观下的取值（Display P3）。
struct RadixP3Color: Hashable, Sendable {
    let light: RadixP3
    let dark: RadixP3

    init(light: RadixP3, dark: RadixP3) {
        self.light = light
        self.dark = dark
    }

    /// 随系统深浅外观自动切换。
    var uiColor: UIColor {
        UIColor { trait in
            Self.makeUIColor(trait.userInterfaceStyle == .dark ? self.dark : self.light)
        }
    }

    /// 在动态色基础上再叠一层透明度 —— 仍然跟随系统深浅。
    ///
    /// 没有写成 `uiColor.withAlphaComponent(value)`：那要赌「系统会不会把动态性一起带过去」。
    /// 这里在外层再包一个动态色 —— 浅深各自解析完，再叠 alpha，不依赖任何假设。
    func alpha(_ value: CGFloat) -> UIColor {
        UIColor { trait in
            let base = Self.makeUIColor(trait.userInterfaceStyle == .dark ? self.dark : self.light)
            return base.withAlphaComponent(value)
        }
    }

    /// 固定取某一种外观下的颜色（**不跟随系统**）。
    func uiColor(for style: UIUserInterfaceStyle) -> UIColor {
        Self.makeUIColor(style == .dark ? dark : light)
    }

    /// `UIColor(displayP3Red:green:blue:alpha:)`（Apple，iOS 10+）。
    private static func makeUIColor(_ value: RadixP3) -> UIColor {
        UIColor(
            displayP3Red: CGFloat(value.red),
            green: CGFloat(value.green),
            blue: CGFloat(value.blue),
            alpha: CGFloat(value.alpha)
        )
    }
}


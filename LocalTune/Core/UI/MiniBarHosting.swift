/// 「能让底部那一块让路」这件事 —— **纯机制，不含任何业务概念**。
///
/// 页面要底部让路时（比如进多选、那一格要摆**系统工具条**），只声明**藏起来**；
/// 它藏在哪、怎么藏、让位怎么办 —— 全是宿主的事，页面一个字都不用知道。
///
/// ⚠️ **为什么是协议、而不是让页面直接认某个容器类型**：宿主住在 `App` 层，
/// 页面住在 `Features` 层，分层是**单向**的 —— 页面不许认识 `App` 里的类型。
/// 协议放在 `Core`，两边都只依赖它。
///
/// ⚠️ 页面找宿主是**顺 `parent` 链往上找最近的那个 `MiniBarHosting`**
/// （见 `BaseViewController.bottomBlockHost`）—— **不写死宿主的类型**，换结构页面不用改。
///
/// 宿主是**每个 tab 的导航容器**（`MiniBarNavController`，条子就住在它里面）；
/// 在那之前宿主是标签栏容器（那里原来写着 `tabBarController as? MiniBarHosting`）。
protocol MiniBarHosting: AnyObject {

    /// 藏 / 放**底部那一整块**（条子 **和** 它底下那层材质）。
    ///
    /// 🔴 **必须整块一起收**：只藏条子是不够的 —— 底下那层材质铺在"条子顶 → 屏幕底"上、
    /// 又压在导航栈内容**之上**，留着它就会把**系统工具条盖住**
    /// （表现：进了多选，工具条"看不见"）。
    ///
    /// ⚠️ 多选时**只藏条子**、标签栏照旧在 —— 这是有意那么做的。
    /// 我们整块收，原因是上面那条（工具条会被盖住）—— 实机踩过。
    ///
    /// ⚠️ 跟**让位无关**：让位是那一个常量，藏不藏都照旧
    /// （见 `MiniBarNavController` 里的让位）—— 那一格还是那一格。
    func setBottomBlockHidden(_ hidden: Bool)
}
